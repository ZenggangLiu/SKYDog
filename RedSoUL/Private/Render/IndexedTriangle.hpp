#pragma once


/// System headers
#include <stdint.h> /// uint16_t,...


/// 使用顶点索引定义的三角面
///
struct IndexedTriangle
{
    /// 三角面的三个顶点依次为A, B, C
    /// 它的法线定义为 N := Cross(AB, AC)
    ///        B
    ///        /\
    ///       /  \  / 法线N
    ///      /    \/
    ///     /     /\
    ///    /     /  \
    ///   /     /    \
    ///  /            \
    /// A ------------- C
    ///
    /// A点的顶点数据索引
    uint16_t idx_a;
    /// B点的顶点数据索引
    uint16_t idx_b;
    /// C点的顶点数据索引
    uint16_t idx_c;
};
